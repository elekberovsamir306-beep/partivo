## Elan yerləşdirmək pulsuzdur?

Bəli. Elan yerləşdirmək pulsuzdur. Ödənişli yalnız elanı daha çox alıcıya göstərən TOP, VIP və PREMIUM xidmətləridir.

## Elanım nə vaxt dərc olunacaq?

Elanlar moderasiyadan keçir. Adətən bu, iş saatlarında bir neçə saat çəkir. Nəticə barədə bildiriş alacaqsınız.

## Neçə şəkil yükləməliyəm?

Hər elanda ən azı 5, ən çoxu 10 şəkil olmalıdır. Hissəni müxtəlif bucaqlardan, etiket və OEM kodu görünəcək şəkildə çəkin.

## OEM kodu nədir və harada tapım?

OEM kodu istehsalçının hissəyə verdiyi orijinal nömrədir. Adətən hissənin üzərində və ya etiketində yazılır. OEM kodu ilə axtarış uyğun hissəni tapmağın ən dəqiq yoludur.

## Elanımın müddəti bitdi, nə etməliyəm?

"Elanlarım" bölməsində elanın yanındakı "Yenilə" düyməsini sıxın. Elan yenidən aktiv olacaq.

## Satıcı ilə necə əlaqə saxlayım?

Elan səhifəsində "Nömrəni göstər" və ya "WhatsApp" düyməsini sıxın. Ödənişi hissəni şəxsən yoxladıqdan sonra etməyiniz tövsiyə olunur.

## Fırıldaqçı elanla rastlaşdım. Nə edim?

Elan səhifəsindəki "Şikayət et" düyməsini sıxın və səbəbi seçin. Moderatorlarımız şikayəti yoxlayacaq. Heç vaxt əvvəlcədən ödəniş etməyin və kart məlumatlarınızı paylaşmayın.

## Ödəniş etdim, amma reklam aktivləşmədi.

Bəzən bankın təsdiqi bir neçə dəqiqə çəkir. Vəziyyəti "Ödənişlər" bölməsində izləyə bilərsiniz. 30 dəqiqədən sonra da aktivləşməyibsə, bizimlə əlaqə saxlayın.

## Hesabımı necə silə bilərəm?

"Hesab" → "Məxfilik və məlumatlar" bölməsində hesabınızı silə və ya məlumatlarınızı yükləyə bilərsiniz.
